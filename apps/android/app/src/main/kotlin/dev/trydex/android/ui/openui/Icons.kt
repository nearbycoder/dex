    /** The same words in any order find the icon (`check-circle` → `circle-check`). */
    private val BY_WORDS: Map<String, String> = ICONS.keys.groupBy { it.split('-').sorted().joinToString("-") }.mapValues { it.value.first() }

    fun kebab(name: String): String = name.trim()
        .replace(Regex("([a-z])([A-Z])"), "$1-$2")
        .replace(Regex("([A-Z])([A-Z][a-z])"), "$1-$2")
        .replace(Regex("[\\s_]+"), "-")
        .replace(Regex("([a-zA-Z])(\\d)"), "$1-$2")
        .lowercase()
        .replace(Regex("-+"), "-")
        .trim('-')

    /** The icon for a lucide name; never null for a non-empty name (the category's icon or a dot stands in). */
    fun resolve(name: String?, category: String? = null): ImageVector? {
        val raw = name?.trim().orEmpty()
        if (raw.isEmpty()) return null
        ICONS[raw]?.let { return it }
        val key = kebab(raw)
        ICONS[key]?.let { return it }
        // Lucide names drop the dash before a digit in some forms (`building2`).
        ICONS[key.replace(Regex("-(\\d)"), "$1")]?.let { return it }
        BY_WORDS[key.split('-').sorted().joinToString("-")]?.let { return ICONS[it] }
        val words = key.split('-')
        for (n in words.size - 1 downTo 1) {
            val prefix = words.take(n).joinToString("-")
            ICONS[prefix]?.let { return it }
        }
        CATEGORIES[category?.trim()?.lowercase()]?.let { return ICONS[it] }
        return ICONS.getValue("circle-dot")
    }
