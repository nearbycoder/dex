// Embeds dizione's hand-written tables (src/dizione/data/*.txt) in src/server/voice/dizione/data.ts, so the Worker
// needs only the built files from Hugging Face. Run it with a checkout of https://github.com/n4ze3m/dizione at the
// commit the port follows:
//
//   node scripts/build-dizione-tables.mjs /path/to/dizione

import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

// The tables the phonemizer reads at run time (homograph_fixes.txt is only for training).
const TABLES = ["abbreviations.txt", "chat.txt", "endings.txt", "exceptions.txt", "function_words.txt", "homograph_rules.txt", "letters.txt", "phrases.txt", "units.txt"]

const checkout = process.argv[2]
if (!checkout) {
  console.error("usage: node scripts/build-dizione-tables.mjs /path/to/dizione")
  process.exit(1)
}
const commit = execFileSync("git", ["-C", checkout, "rev-parse", "HEAD"], { encoding: "utf8" }).trim()
const entries = TABLES.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(checkout, "src/dizione/data", name), "utf8"))}`)
const output = new URL("../src/server/voice/dizione/data.ts", import.meta.url)
writeFileSync(output, `// Generated by scripts/build-dizione-tables.mjs from dizione's src/dizione/data. Do not edit.

/** The dizione commit the tables and the port follow. */
export const DIZIONE_COMMIT = ${JSON.stringify(commit)}

export const TABLES = {
${entries.join(",\n")}
} as const
`)
console.log(`wrote ${output.pathname} from dizione ${commit}`)
